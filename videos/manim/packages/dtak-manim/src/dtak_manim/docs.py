"""Generate STORYBOARD.md and SCRIPT.md from an episode's beats YAML.

The YAML files are the source of truth; the Markdown files are build products
for reading (and for the person who records the voice). Do not edit them.
"""

from __future__ import annotations

from dtak_manim.episode import Episode

HEADER = "<!-- Generated by `dtak docs {slug}` from beats/*.yaml. Do not edit: edit the YAML. -->\n\n"


def _mmss(seconds: float) -> str:
    return f"{int(seconds // 60)}:{int(seconds % 60):02d}"


def storyboard(ep: Episode) -> str:
    out = [HEADER.format(slug=ep.slug), f"# Storyboard: {ep.title}\n\n"]
    if ep.subtitle or ep.byline:
        out.append(f"Title slide: **{ep.title}**" + (f" · *{ep.subtitle}*" if ep.subtitle else "")
                   + (f" · {ep.byline}" if ep.byline else "") + "\n\n")
    out.append(
        "What is on screen, beat by beat. Beat IDs are shared with SCRIPT.md, the "
        "`@beat(\"…\")` scene methods and the clip names of "
        "`dtak render --sections`.\n"
    )
    for s in ep.sections:
        card = " (opens with a navy section card)" if s.card else ""
        out.append(f"\n## {s.number} · {s.title}\n\n`{s.module}` → `{s.scene}`{card}"
                   + (f". Card subtitle: *{s.subtitle}*." if s.subtitle else ".") + "\n")
        for b in s.beats:
            out.append(f"\n### {b.id} {b.title}\n\n{b.visual}\n")
    return "".join(out)


def script(ep: Episode) -> str:
    total = sum(b.seconds(ep.wpm) for s in ep.sections for b in s.beats)
    out = [HEADER.format(slug=ep.slug), f"# Script: {ep.title}\n\n"]
    out.append(
        f"Narration for each beat, read at ~{ep.wpm:.0f} words per minute "
        f"(narration alone: about **{_mmss(total)}**). The animation of each beat lasts at "
        "least as long as its narration (manim-voiceover). `[n]` are entries of "
        "REFERENCES.md and are not read aloud.\n"
    )
    t = 0.0
    for s in ep.sections:
        out.append(f"\n## {s.number} · {s.title}\n")
        for b in s.beats:
            secs = b.seconds(ep.wpm)
            refs = " ".join(f"[{r}]" for r in b.refs)
            out.append(f"\n### {b.id} {b.title}  ·  {_mmss(t)} (+{secs:.0f} s)\n\n{b.narration}\n")
            if refs:
                out.append(f"\n*Sources: {refs}*\n")
            t += secs
    return "".join(out)


def write_docs(ep: Episode) -> list[str]:
    paths = []
    for name, text in (("STORYBOARD.md", storyboard(ep)), ("SCRIPT.md", script(ep))):
        p = ep.root / name
        p.write_text(text)
        paths.append(str(p))
    return paths
